-- =========================================================
-- Sistema de Inscrições em Eventos
-- Estrutura compatível com os modelos da aplicação Django
-- Banco de dados: PostgreSQL
-- =========================================================

-- Remove primeiro a tabela dependente
DROP TABLE IF EXISTS api_inscricao;
DROP TABLE IF EXISTS api_evento;

-- =========================================================
-- TABELA: api_evento
-- =========================================================

CREATE TABLE api_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT NOT NULL,
    palestrante VARCHAR(200) NOT NULL,
    local VARCHAR(200) NOT NULL,
    data_inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    data_fim TIMESTAMP WITH TIME ZONE NOT NULL,
    capacidade INTEGER NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT api_evento_pkey
        PRIMARY KEY (id),

    CONSTRAINT evento_capacidade_maior_que_zero
        CHECK (capacidade > 0),

    CONSTRAINT evento_data_fim_apos_inicio
        CHECK (data_fim > data_inicio)
);

-- =========================================================
-- TABELA: api_inscricao
-- =========================================================

CREATE TABLE api_inscricao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    participante_nome VARCHAR(200) NOT NULL,
    participante_email VARCHAR(254) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmada',
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    evento_id BIGINT NOT NULL,

    CONSTRAINT api_inscricao_pkey
        PRIMARY KEY (id),

    CONSTRAINT api_inscricao_evento_fk
        FOREIGN KEY (evento_id)
        REFERENCES api_evento (id)
        ON DELETE CASCADE,

    CONSTRAINT inscricao_evento_email_unicos
        UNIQUE (evento_id, participante_email),

    CONSTRAINT inscricao_status_valido
        CHECK (status IN ('confirmada'))
);

-- Índice para agilizar a busca das inscrições por evento
CREATE INDEX api_inscricao_evento_id_idx
    ON api_inscricao (evento_id);

-- Índice para organizar e consultar eventos pela data de início
CREATE INDEX api_evento_data_inicio_idx
    ON api_evento (data_inicio);

-- =========================================================
-- CONTROLE DO LIMITE DE VAGAS
-- =========================================================

CREATE OR REPLACE FUNCTION verificar_capacidade_evento()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    capacidade_evento INTEGER;
    total_inscricoes INTEGER;
BEGIN
    -- Bloqueia o evento durante a verificação para evitar que
    -- duas pessoas ocupem simultaneamente a última vaga.

    SELECT capacidade
    INTO capacidade_evento
    FROM api_evento
    WHERE id = NEW.evento_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'O evento informado não existe.';
    END IF;

    SELECT COUNT(*)
    INTO total_inscricoes
    FROM api_inscricao
    WHERE evento_id = NEW.evento_id
      AND status = 'confirmada'
      AND (
          TG_OP = 'INSERT'
          OR id <> NEW.id
      );

    IF total_inscricoes >= capacidade_evento THEN
        RAISE EXCEPTION
            'O evento atingiu o limite de vagas.';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_verificar_capacidade_evento
BEFORE INSERT OR UPDATE OF evento_id, status
ON api_inscricao
FOR EACH ROW
EXECUTE FUNCTION verificar_capacidade_evento();
